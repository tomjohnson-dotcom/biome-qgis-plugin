# Years to enhance baseline condition -> target condition (G-7 T5:Y9). "N/A"
# entries (a downgrade) are omitted. Same for every watercourse type.
WATER_ENHANCEMENT_YEARS = {
    ("Poor", "Poor"): 1, ("Poor", "Fairly Poor"): 2, ("Poor", "Moderate"): 4,
    ("Poor", "Fairly Good"): 6, ("Poor", "Good"): 8,
    ("Fairly Poor", "Fairly Poor"): 1, ("Fairly Poor", "Moderate"): 2,
    ("Fairly Poor", "Fairly Good"): 4, ("Fairly Poor", "Good"): 6,
    ("Moderate", "Moderate"): 1, ("Moderate", "Fairly Good"): 2,
    ("Moderate", "Good"): 4,
    ("Fairly Good", "Fairly Good"): 1, ("Fairly Good", "Good"): 2,
    ("Good", "Good"): 1,
}


# Establishment years for a watercourse enhancement that moves to a HIGHER
# distinctiveness habitat (metric G-7 R3 — the "Lower Distinctiveness Habitat"
# pathway, used instead of the condition->condition table when dist goes up).
WATER_ENH_DIST_UPLIFT_YEARS = 10


def water_enhancement_multiplier(proposed_type, start_condition, target_condition,
                                 baseline_type=None):
    """Temporal x difficulty for ENHANCING a watercourse reach (metric C-3
    AH x AD), to blend via blend_enhanced_units (baseline value kept whole, only
    the uplift discounted).

    Years-to-target follow the metric: a distinctiveness UPLIFT (proposed dist >
    baseline dist) takes the fixed R3 establishment period; otherwise the
    baseline->target condition table. Difficulty is the PROPOSED type's
    enhancement difficulty (G-7 col F). Returns None if the proposed type is not
    an enhanceable watercourse type or the step has no years entry."""
    pt = _norm(proposed_type)
    if pt not in WATER_ENHANCEMENT_DIFFICULTY:
        return None
    years = None
    if baseline_type:
        try:
            from .habitat_data import DISTINCTIVENESS_SCORES as _DS
            if _DS.get(pt, 0) > _DS.get(_norm(baseline_type), 0):
                years = WATER_ENH_DIST_UPLIFT_YEARS
        except Exception:
            pass
    if years is None:
        years = WATER_ENHANCEMENT_YEARS.get((_norm(start_condition),
                                             _norm(target_condition)))
    if years is None:
        return None
    tm = _temporal(years)
    if tm is None:
        return None
    df = _DIFFICULTY_CATEGORY_MULT.get(WATER_ENHANCEMENT_DIFFICULTY[pt], 1.0)
    return tm * df


def water_enhancement_allowed(baseline_type, proposed_type):
    """Watercourse ENHANCEMENT trading (metric C-3 O/P + G-7 col G):

      * a reach may be enhanced to a habitat of the SAME or HIGHER
        distinctiveness — never trading down (proposed dist >= baseline dist).
      * a Culvert (lowest distinctiveness, condition locked at Poor so no
        condition uplift is possible) can ONLY be enhanced by moving to a
        STRICTLY HIGHER distinctiveness habitat (G-7 "Better distinctiveness
        habitat required").

    Whether a change is an *improvement* (condition up or distinctiveness up) is
    decided by the classifier's better/worse test; this predicate only gates
    which 'better' changes count as enhancement vs creation. A condition drop is
    'worse' and becomes lost + created regardless."""
    bt = _norm(baseline_type)
    pt = _norm(proposed_type)
    if bt not in WATER_TYPES or pt not in WATER_TYPES:
        return False
    try:
        from .habitat_data import DISTINCTIVENESS_SCORES as _DS
    except Exception:
        return bt == pt
    bd = _DS.get(bt, 0)
    pd = _DS.get(pt, 0)
    if bt == "Culvert":
        return pd > bd
    return pd >= bd


def _temporal(years):
    if years is None:
        return None
    if isinstance(years, str):
        # "30+" has its own dedicated multiplier in the metric's G-4 table,
        # distinct from the plain 30-year value.
        if years.strip().startswith("30"):
            return PLUS30_MULTIPLIER
        try:
            years = float(years)
        except (ValueError, TypeError):
            return None
    return TEMPORAL_DISCOUNT ** float(years)


def creation_temporal_multiplier(habitat, target_condition):
    """0.965 ** (years to reach target condition by creation). None if not possible."""
    row = _CREATE_YEARS.get(_full(habitat))
    if not row:
        return None
    return _temporal(row.get(_norm(target_condition)))


def enhancement_temporal_multiplier(habitat, start_condition, target_condition):
    """0.965 ** (years to enhance start_condition -> target_condition). None if not possible."""
    row = _ENHANCE_YEARS.get(_full(habitat))
    if not row:
        return None
    key = "%s - %s" % (_norm(start_condition), _norm(target_condition))
    return _temporal(row.get(key))


def difficulty_creation(habitat):
    return _DIFF_CREATE.get(_full(habitat), 1.0)


def difficulty_enhancement(habitat):
    return _DIFF_ENHANCE.get(_full(habitat), 1.0)


def years_to_target(change_type, habitat, target_condition,
                    start_condition=None, baseline_habitat=None):
    """Integer years-to-target (or the string '30+', or None) for an AREA
    create / enhance move, read from the SAME tables proposed_multiplier selects
    from. None == the metric has no pathway for this change.

    Used by the on-site enhancement engine to gate moves on a time-to-target cap
    and to badge establishment time. Hedgerow / watercourse are not handled here
    (area module only) — callers needing those should use their own tables."""
    ct = (change_type or "").lower()
    if ct in ("created", "creation", "create"):
        row = _CREATE_YEARS.get(_full(habitat))
        return row.get(_norm(target_condition)) if row else None
    if ct in ("enhanced", "enhancement", "enhance"):
        start = start_condition
        # A habitat CHANGE to a higher-distinctiveness type uses the metric's
        # "Lower Distinctiveness Habitat -> <target condition>" row (mirrors
        # proposed_multiplier), not the condition-to-condition row.
        if baseline_habitat and baseline_habitat != habitat:
            try:
                from .habitat_data import DISTINCTIVENESS_SCORES as _DS
                if _DS.get(habitat, 0) > _DS.get(baseline_habitat, 0):
                    start = "Lower Distinctiveness Habitat"
            except Exception:
                pass
        row = _ENHANCE_YEARS.get(_full(habitat))
        if not row:
            return None
        return row.get("%s - %s" % (_norm(start), _norm(target_condition)))
    return None


def blend_enhanced_units(baseline_value, proposed_value, mult):
    """Metric-correct ENHANCEMENT units.

    The statutory metric keeps the parcel's existing (baseline) value WHOLE and
    time-discounts only the *uplift* — it mirrors A-3 'Habitat units delivered':

        delivered = baseline_value + (proposed_value - baseline_value) * mult

    where ``mult`` is the temporal x difficulty multiplier from
    ``proposed_multiplier('enhanced', ...)``. This differs from CREATION, where
    the whole proposed value is discounted (no baseline to keep) — for which you
    pass ``baseline_value = 0`` and recover ``proposed_value * mult``.

    Using ``proposed_value * mult`` for enhancement (the old summary behaviour)
    wrongly discounts the baseline portion too, under-counting every enhancement
    and, at long delays, collapsing a retained-and-improved habitat to zero.
    """
    return baseline_value + (proposed_value - baseline_value) * mult


_NOT_HEDGE = object()   # sentinel: habitat is not a hedgerow type


def _hedge_years(change_type, habitat, target_condition, start_condition,
                 baseline_habitat):
    """Years-to-target for a hedgerow create/enhance from the metric G-6 tables.
    Returns _NOT_HEDGE if `habitat` is not a hedge type (caller falls through to
    the area path); an int / "30+" if it is; or None if the change is not
    possible for that hedge."""
    try:
        from .hedge_temporal_data import (HEDGE_CREATION_YEARS,
                                          HEDGE_ENH_COND_YEARS,
                                          HEDGE_ENH_DIST_YEARS)
    except Exception:
        return _NOT_HEDGE
    if habitat not in HEDGE_CREATION_YEARS:
        return _NOT_HEDGE
    ct = (change_type or "").lower()
    if ct in ("created", "creation", "create"):
        return HEDGE_CREATION_YEARS.get(habitat, {}).get(target_condition)
    if ct in ("enhanced", "enhancement", "enhance"):
        if baseline_habitat and baseline_habitat != habitat:
            # habitat change -> enhancement-through-distinctiveness matrix
            return HEDGE_ENH_DIST_YEARS.get((baseline_habitat, habitat))
        # same hedge type -> enhancement-through-condition
        key = "%s - %s" % (_norm(start_condition), _norm(target_condition))
        return HEDGE_ENH_COND_YEARS.get(habitat, {}).get(key)
    return _NOT_HEDGE


def hedge_enhancement_allowed(baseline_type, proposed_type):
    """True if the metric (G-6 Hedgerow Data) accepts baseline_type ->
    proposed_type as a hedgerow ENHANCEMENT. A same-type change (condition
    uplift) is always allowed; a cross-type change is allowed only if it is a
    non-error cell in habitat_data.HEDGE_ENHANCEMENT_OK. Anything else ("Trading
    Down" or "Enhancement not possible") must be treated as CREATION — e.g. a
    Non-native and ornamental hedgerow can never be enhanced into a native one."""
    if not baseline_type or baseline_type == proposed_type:
        return True
    try:
        from .habitat_data import HEDGE_ENHANCEMENT_OK
    except Exception:
        return True
    return (baseline_type, proposed_type) in HEDGE_ENHANCEMENT_OK


def area_enhancement_allowed(baseline_sub, baseline_cond, proposed_sub, proposed_cond):
    """True if the metric accepts this AREA change as ENHANCEMENT (A-3 trading
    rule, set by the BASELINE distinctiveness — verified against the A-3
    'Required Action' column):

      * same habitat  -> always allowed (condition uplift).
      * baseline High or Very High -> a habitat CHANGE is NOT enhancement
        ("Same habitat required ="); it must be creation. Only a condition
        uplift of the same habitat qualifies.
      * baseline Low / Medium -> a change to a higher-or-equal distinctiveness
        habitat in the same broad group IS enhancement, provided the metric has
        an enhancement pathway for it (G-5 'Lower Distinctiveness Habitat' row).
    """
    if not baseline_sub or baseline_sub == proposed_sub:
        return True
    try:
        from .habitat_data import DISTINCTIVENESS_SCORES as _DS
    except Exception:
        return True
    bd = _DS.get(baseline_sub, 0)
    pd = _DS.get(proposed_sub, 0)
    if bd >= 6:                      # High / Very High -> same specific habitat only
        return False
    if pd < bd:                      # trading down is not enhancement
        return False
    return enhancement_temporal_multiplier(
        proposed_sub, "Lower Distinctiveness Habitat", proposed_cond) is not None


def proposed_multiplier(change_type, habitat, target_condition,
                        start_condition=None, baseline_habitat=None):
    """
    Combined NON-area multiplier to apply to a PROPOSED parcel on top of
    (distinctiveness x condition x strategic significance).

    change_type: 'retained' | 'created' | 'enhanced'
    baseline_habitat: for ENHANCEMENT, the baseline (start) habitat. When the
        enhancement CHANGES habitat to a higher-distinctiveness one in the same
        broad group, the metric (A-3 col U) looks up the temporal under the
        "Lower Distinctiveness Habitat -> <target condition>" row rather than the
        condition-to-condition row. We mirror that here so a same-condition
        distinctiveness uplift still carries its establishment temporal instead
        of being scored at full value.
    Returns (multiplier, note). note is '' unless something needs flagging.
    """
    ct = (change_type or "").lower()
    if ct in ("retained", "retain", "baseline", ""):
        return 1.0, ""

    # ── HEDGEROW temporals (metric G-6 — separate year tables from area) ──────
    # Years to target come from G-6 (creation E/G/I, enhancement-through-
    # condition K/M/Q, enhancement-through-distinctiveness S-AE); the multiplier
    # is the shared 0.965**years. All G-6 hedge difficulties are "Low" (=1.0).
    _hy = _hedge_years(ct, habitat, target_condition, start_condition, baseline_habitat)
    if _hy is not _NOT_HEDGE:
        tm = _temporal(_hy)
        if tm is None:
            return 1.0, ("hedge '%s' -> '%s' not possible - temporal not applied"
                         % (_norm(start_condition or habitat), _norm(target_condition)))
        return tm, ""

    # ── WATERCOURSE temporals + difficulty (metric C-2 / G-7) ─────────────────
    # Watercourse habitats are not in the area creation/enhancement year tables,
    # so without this branch their proposed multiplier defaults to 1.0 and
    # CREATED reaches over-count ~4x (no difficulty, no time-to-target).
    if _norm(habitat) in WATER_CREATION_DIFFICULTY:
        if ct in ("created", "creation", "create"):
            wm = water_creation_multiplier(habitat, target_condition)
            if wm is None:
                return 1.0, ("watercourse creation to '%s' not possible - "
                             "temporal not applied" % _norm(target_condition))
            return wm, ""
        if ct in ("enhanced", "enhancement", "enhance"):
            wm = water_enhancement_multiplier(habitat, start_condition,
                                              target_condition,
                                              baseline_type=baseline_habitat)
            if wm is None:
                return 1.0, ("watercourse enhancement '%s'->'%s' not possible - "
                             "temporal not applied"
                             % (_norm(start_condition), _norm(target_condition)))
            return wm, ""
        return 1.0, ""

    if ct in ("created", "creation", "create"):
        tm = creation_temporal_multiplier(habitat, target_condition)
        df = difficulty_creation(habitat)
        if tm is None:
            return df, "creation not possible to '%s' - temporal not applied" % _norm(target_condition)
        return tm * df, ""
    if ct in ("enhanced", "enhancement", "enhance"):
        temporal_start = start_condition
        if baseline_habitat and baseline_habitat != habitat:
            try:
                from .habitat_data import DISTINCTIVENESS_SCORES as _DS
                if _DS.get(habitat, 0) > _DS.get(baseline_habitat, 0):
                    temporal_start = "Lower Distinctiveness Habitat"
            except Exception:
                pass
        tm = enhancement_temporal_multiplier(habitat, temporal_start, target_condition)
        df = difficulty_enhancement(habitat)
        if tm is None:
            return df, "enhancement '%s'->'%s' not in lookup - temporal not applied" % (
                _norm(temporal_start), _norm(target_condition))
        return tm * df, ""
    return 1.0, "unknown change_type '%s'" % change_type


