"""
bng_multipliers.py  -- standard Statutory Biodiversity Metric multipliers.

Data tables extracted verbatim from "The Statutory Metric" workbook:
  - strategic significance      (G-3 / metric rules)
  - technical difficulty        (G-3 Multipliers: creation & enhancement)
  - creation time-to-target     (G-4 Temporal multipliers)
  - enhancement time-to-target  (G-5 Enhancement Temporal)

Temporal multiplier = TEMPORAL_DISCOUNT ** years_to_target  (3.5% p.a., i.e. 0.965).
Retained habitat gets NO temporal/difficulty multiplier.
Created habitat  gets creation temporal x creation difficulty.
Enhanced habitat gets enhancement temporal x enhancement difficulty.

Habitat keys are the metric's full "Group - SubType" labels; helpers also accept
the bare sub-habitat-type used by the layers (mapped via _SUB2FULL).

VERSION / SOURCE OF TRUTH
-------------------------
These tables are a manual transcription of the DEFRA Statutory Biodiversity
Metric. The bundled ``BNG_Metric_Template.xlsm`` is the authoritative source
(its "Version History" tab holds the exact metric version); the exported
spreadsheet — not this module — is what the user relies on for statutory
numbers. This module only powers the in-plugin *preview*.
  * Template last synced: 2025-07-04 (BNG_Metric_Template.xlsm mtime).
  * If DEFRA release a new metric version, replace the template AND re-check
    these tables (G-3 Multipliers, G-4/G-5 Temporal, strategic significance)
    against it — there is no automatic drift detection.
"""

